using NpgsqlTypes;
using Pgvector;

namespace eShop.Policy.API.Infrastructure;

/// <summary>A Policy as it was last indexed, keyed by the slug of its file name.</summary>
public class IndexedPolicy
{
    public required string Slug { get; set; }

    public required string Title { get; set; }

    public required string Category { get; set; }

    /// <summary>The <c>last_updated</c> value from front matter, kept for display only.</summary>
    public string? LastUpdated { get; set; }

    /// <summary>SHA-256 of the file bytes, in hex.</summary>
    public required string ContentHash { get; set; }

    /// <summary>The embedding model the Policy was indexed with, or <see cref="PolicyIngestion.NoEmbeddingModel"/>.</summary>
    public required string EmbeddingModelId { get; set; }

    public DateTimeOffset IndexedAt { get; set; }

    public List<IndexedPolicySection> Sections { get; set; } = [];
}

/// <summary>A Policy Section as stored for search.</summary>
public class IndexedPolicySection
{
    public int Id { get; set; }

    public required string PolicySlug { get; set; }

    /// <summary>Order within the Policy, from 0.</summary>
    public int Position { get; set; }

    public required string Heading { get; set; }

    public required string Anchor { get; set; }

    public required string Body { get; set; }

    /// <summary><c>"{Policy title} › {heading}"</c> followed by the body: what is embedded and searched.</summary>
    public required string IndexedText { get; set; }

    /// <summary>Null until an embedding provider is configured.</summary>
    public Vector? Embedding { get; set; }

    /// <summary>Generated by Postgres from <see cref="IndexedText"/> with the English configuration.</summary>
    public NpgsqlTsVector SearchVector { get; set; } = null!;
}
